const {test}=require('node:test');
const assert=require('node:assert/strict');
const {randomUUID}=require('node:crypto');
const express=require('express');
require('dotenv').config();
const {env}=require('../dist/config/env.js');
const {prisma}=require('../dist/config/db.js');
const delivery=require('../dist/modules/taxes/tax-delivery.js');
const routes=require('../dist/modules/taxes/tax.routes.js').default;
const {errorHandler}=require('../dist/middlewares/error.middleware.js');
require('../dist/utils/logger.js').logger.silent=true;
test('Marketing reads branch taxes and deliveries; ADMIN Marketing may write and resync',async(t)=>{
 const branch=randomUUID(),id=randomUUID();
 const profile={id,officeBranchId:branch,isActive:true,role:'USER',section:'MARKETING',firstName:'Test',lastName:'User',username:'test'};
 const originalFetch=global.fetch,findTaxes=prisma.tax.findMany,findDeliveries=prisma.taxDelivery.findMany,processDeliveries=delivery.processDueTaxDeliveries;
 global.fetch=async()=>({ok:true,json:async()=>({data:profile})});
 prisma.tax.findMany=async args=>{assert.equal(args.where.officeBranchId,branch);return [];};
 prisma.taxDelivery.findMany=async args=>{assert.equal(args.where.event.officeBranchId,branch);return [];};
 delivery.processDueTaxDeliveries=async selected=>assert.equal(selected,branch);
 const app=express();app.use(express.json());app.use((req,res,next)=>{req.user={sub:id,officeBranchId:branch};next();});app.use('/taxes',routes);app.use(errorHandler);
 const server=await new Promise(resolve=>{const s=app.listen(0,'127.0.0.1',()=>resolve(s));});
 t.after(async()=>{global.fetch=originalFetch;prisma.tax.findMany=findTaxes;prisma.taxDelivery.findMany=findDeliveries;delivery.processDueTaxDeliveries=processDeliveries;await new Promise(resolve=>server.close(resolve));});
 const request=async(method,path,status,body)=>{const r=await originalFetch(`http://127.0.0.1:${server.address().port}/taxes${path}`,{method,headers:{authorization:'Bearer valid','content-type':'application/json'},...(method==='GET'?{}:{body:JSON.stringify(body)})});assert.equal(r.status,status,await r.text());};
 await request('GET','',200);await request('GET','/deliveries',200);
 await request('POST','',403,{});await request('POST','/resync',403,{});
 profile.role='ADMIN';await request('POST','',400,{});await request('POST','/resync',400,{unexpected:true});
 profile.role='USER';profile.section='HRD_MANAGEMENT';await request('GET','',403);
 profile.section='MARKETING';profile.isActive=false;await request('GET','',403);
});
